#!/usr/bin/env node

/**
 * generate-ambassador-codes.js
 *
 * Generates unique, cryptographically random ambassador referral codes
 * and writes them to src/lib/ambassador-codes.js.
 *
 * Format: d26-[shortcode]-[4-char hex]
 *
 * IMPORTANT: This script is one-shot. If ambassador-codes.js already
 * exists, it will refuse to run to prevent overwriting existing codes.
 *
 * Usage: node generate-ambassador-codes.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const OUTPUT_PATH = path.join(__dirname, 'src', 'lib', 'ambassador-codes.js');

// Institution list: [Full Name, Short Code]
const INSTITUTIONS = [
  ['IIT Bombay', 'iitb'],
  ['IIT Kharagpur', 'iitk'],
  ['IIT Delhi', 'iitd'],
  ['IIT Madras', 'iitm'],
  ['IIT Roorkee', 'iitr'],
  ['IIT Guwahati', 'iitg'],
  ['IIT Hyderabad', 'iith'],
  ['IIT Kanpur', 'iitk2'],
  ['BITS Pilani', 'bitsp'],
  ['BITS Goa', 'bitsg'],
  ['BITS Hyderabad', 'bitsh'],
  ['IISc Bangalore', 'iisc'],
  ['NIT Trichy', 'nitt'],
  ['NIT Warangal', 'nitw'],
  ['NIT Surathkal', 'nitk'],
  ['NIT Patna', 'nitp'],
  ['NIT Srinagar', 'nits'],
  ['IIIT Hyderabad', 'iiith'],
  ['NSUT Delhi', 'nsut'],
  ['DTU Delhi', 'dtu'],
  ['TSEC Mumbai', 'tsec'],
  ['ICT Mumbai', 'ict'],
  ['VIT Vellore', 'vit'],
  ['Manipal', 'mahe'],
];

// ── Guard: never overwrite existing codes ──────────────────────────────────
if (fs.existsSync(OUTPUT_PATH)) {
  console.log('Codes already generated. Do not run again.');
  process.exit(0);
}

// ── Generate codes ─────────────────────────────────────────────────────────
const entries = INSTITUTIONS.map(([name, shortcode]) => {
  const hex = crypto.randomBytes(2).toString('hex'); // 4-char hex
  const code = `d26-${shortcode}-${hex}`;
  const link = `amsderive.in?ref=${code}`;
  return { name, shortcode, code, link };
});

// ── Print console table ────────────────────────────────────────────────────
const maxName = Math.max(...entries.map((e) => e.name.length), 'Institution'.length);
const maxCode = Math.max(...entries.map((e) => e.code.length), 'Code'.length);
const maxLink = Math.max(...entries.map((e) => e.link.length), 'Full Link'.length);

const pad = (s, len) => s + ' '.repeat(Math.max(0, len - s.length));
const hr = '-'.repeat(maxName) + ' | ' + '-'.repeat(maxCode) + ' | ' + '-'.repeat(maxLink);

console.log('');
console.log(pad('Institution', maxName) + ' | ' + pad('Code', maxCode) + ' | ' + pad('Full Link', maxLink));
console.log(hr);
entries.forEach((e) => {
  console.log(pad(e.name, maxName) + ' | ' + pad(e.code, maxCode) + ' | ' + pad(e.link, maxLink));
});
console.log('');

// ── Write ambassador-codes.js ──────────────────────────────────────────────
const refMapEntries = entries
  .map((e) => `  '${e.code}': '${e.name}',`)
  .join('\n');

const linksEntries = entries
  .map((e) => `  '${e.name}': '${e.link}',`)
  .join('\n');

const fileContent = `/**
 * Auto-generated by generate-ambassador-codes.js
 * Generated at: ${new Date().toISOString()}
 *
 * DO NOT EDIT MANUALLY. DO NOT REGENERATE.
 * These codes have been distributed to ambassadors.
 */

export const AMBASSADOR_REF_MAP = {
${refMapEntries}
};

export const AMBASSADOR_LINKS = {
${linksEntries}
};

export const PENDING_AMBASSADORS = [];
`;

fs.writeFileSync(OUTPUT_PATH, fileContent, 'utf-8');
console.log(`✓ Written to ${OUTPUT_PATH}`);
console.log('');
